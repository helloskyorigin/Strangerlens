import assert from "node:assert/strict";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { readFileSync } from "node:fs";
import { adaptReport } from "../lib/report-adapter";
import { mapBackendToFrontend } from "../lib/mapper";
import { paymentAnalysis,paymentSnapshot } from "./fixtures/payment-report";
import RecheckComparison,{ summarizeScores,compareScores } from "../components/RecheckComparison";
import ImprovementChecklist from "../components/ImprovementChecklist";
import {buildPremiumWorkbench} from "../lib/premium-workbench";

const mapped=mapBackendToFrontend(structuredClone(paymentAnalysis),"https://example.com",paymentSnapshot);
const report=adaptReport(mapped);
const id1="11111111-1111-4111-8111-111111111111";
const id2="22222222-2222-4222-8222-222222222222";
const prev=summarizeScores(report,id1);
assert.ok(prev&&prev.domain==="example.com");
const updated=structuredClone(prev!);updated.reportId=id2;
updated.overall=(prev!.overall??50)+3;
const diff=compareScores(prev!,updated);
assert.equal(diff?.total,3);
assert.equal(compareScores(prev!,prev!),null,"Reopened report cannot be called a new comparison");
assert.equal(compareScores(prev!,{...updated,domain:"other.com"}),null,"Comparisons never cross domains");
const rendered=renderToStaticMarkup(<RecheckComparison report={report} reportId={id1} onRecheck={()=>{}}/>);
assert.ok(rendered.includes("Recheck &amp; Compare")&&rendered.includes("Recheck website"));
assert.ok(readFileSync("components/RecheckComparison.tsx","utf8").includes("saved privately on this device"),"Device-only persistence notice is present once client state hydrates.");
const workbench=buildPremiumWorkbench(structuredClone(paymentAnalysis),paymentSnapshot);
const checklist=renderToStaticMarkup(<ImprovementChecklist workbench={workbench} reportId={id1}/>);
assert.ok(checklist.includes("Your Fix Checklist"));
assert.ok(checklist.includes('type="checkbox"'));
assert.ok(!checklist.includes("sl_ent_"),"Never render report tokens in fix tracking");
const flow=readFileSync("lib/ui-funnel-events.ts","utf8");
assert.ok(flow.includes('credentials: "omit"')&&flow.includes("navigator?.doNotTrack"),"Anonymous tracking does not send credentials and honors DNT");
const storage=readFileSync("app/api/analytics/funnel/route.ts","utf8");
assert.ok(storage.includes('STRANGERLENS_ANALYTICS_SECRET')&&storage.includes('if(Object.keys(parsed).length!==1)'),"Aggregate analytics validates payload and restricts access");
assert.ok(!storage.includes('body.reportId')&&!storage.includes('body.email'),"No report identifiers or email tracked");
console.log("PASS: same-domain score comparisons, paid checklist, private scores-only persistence and anonymous owner-only funnel.");
