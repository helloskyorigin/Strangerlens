import assert from "node:assert/strict";
import React from "react";
import { readFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import { JSDOM } from "jsdom";
import ScanScreen, { SCAN_FOCUS_MESSAGES, SCAN_STAGES } from "../components/ScanScreen";
import ResultsScreen from "../components/ResultsScreen";
import PurchaseReadinessDeepDive from "../components/PurchaseReadinessDeepDive";
import { mapBackendToFrontend } from "../lib/mapper";
import { extractWebsiteSnapshot } from "../lib/content-extractor";
import { assessPurchaseReadiness } from "../services/scoring/purchaseReadiness";
import { redactAnalysisForFreeTier } from "../server/security/reportAccess";
import { paymentAnalysis, paymentSnapshot } from "./fixtures/payment-report";

const scan = renderToStaticMarkup(<ScanScreen rawUrl="https://example.com" isVerifying onBackToLanding={()=>{}}/>);
const scanSource = readFileSync("components/ScanScreen.tsx", "utf8");
assert.ok(!/home[ -]?page|scaneye/i.test(scanSource), "Scanning never uses the old scope wording or eye icon.");
assert.ok(scan.includes('sl-brand-mark') && scanSource.includes("<BrandMark className=\"h-[65px]"), "Moving focus is the real site logo.");
assert.ok(scanSource.includes("prefers")===false || scanSource.includes("reduceMotion"), "Logo motion honors accessibility setting.");
assert.ok(scanSource.includes("reduceMotion") && scanSource.includes("repeat: Infinity"), "Activity animation only runs when motion is allowed.");
assert.equal(SCAN_STAGES.length,4);
assert.equal(SCAN_FOCUS_MESSAGES.length,4);
assert.ok(SCAN_STAGES.every(stage=>!/home[ -]?page/i.test(stage.label)));

const html='<html><body><main><section><h1>Team reports, made easy</h1><p>Our paid plans include 20 reports and 5 seats. Save time every week.</p><a href="/pricing">Pro plans</a></section><section id="pricing"><h2>Paid plans</h2><p>Pro plan $19/month</p><p>Cancel anytime. Contact support with questions.</p><a href="/checkout">Buy now</a></section></main></body></html>';
const snapshot=extractWebsiteSnapshot(html,{baseUrl:"https://example.com"});
const purchase=assessPurchaseReadiness(snapshot);
assert.ok(purchase?.details);
const details=purchase.details;
assert.equal(details.dimensions.length,5,"All five purchase checks are scored.");
assert.equal(details.dimensions.reduce((a,x)=>a+x.points,0),purchase.score,"Separate score uses only real checks.");
const view=renderToStaticMarkup(<PurchaseReadinessDeepDive details={details}/>);
const doc=new JSDOM(view).window.document;
assert.equal(doc.querySelectorAll('[data-purchase-dimension]').length,5,"Full buyer decision dashboard shows all five dimensions.");
assert.equal(doc.querySelectorAll('[role="progressbar"]').length,5);
assert.ok(view.includes("Observed Website Evidence") && view.includes("BUYER DECISION ANALYSIS"));
assert.ok(view.includes("What to improve first") || view.includes("All five checks have clear"));
assert.ok(view.includes("/20") && view.includes("not a conversion forecast"));
const observed=new Set(details.dimensions.flatMap(x=>x.evidence.map(y=>y.text)));
const displayed=[...doc.querySelectorAll(".sl-purchase-evidence blockquote")].map(x=>x.textContent?.replace(/[“”]/g,"").trim());
assert.ok(displayed.every(x=>x&&observed.has(x)), "Only actual observed source wording may be quoted.");
assert.ok(!view.includes("conversion rate of 20%"), "No invented conversion metric.");
const full={...structuredClone(paymentAnalysis),purchase_readiness:purchase};
const paid=renderToStaticMarkup(<ResultsScreen analysisData={mapBackendToFrontend(full,"https://example.com",snapshot)} isUnlocked/>);
assert.ok(paid.includes("Purchase Readiness →") && !paid.includes('data-testid="purchase-readiness-locked"'),"Verified result shows a direct purchase chapter jump.");
const free=renderToStaticMarkup(<ResultsScreen analysisData={mapBackendToFrontend(redactAnalysisForFreeTier(full),"https://example.com",snapshot)} isUnlocked={false}/>);
assert.ok(!free.includes('data-testid="purchase-decision-deep-dive"') && !free.includes("Purchase Readiness →"),"Unpaid results never expose the buyer diagnosis.");
assert.ok(free.includes('data-testid="purchase-readiness-locked"'),"Unpaid sixth remains independently locked.");
console.log("PASS: brand-led scanning, no homepage copy, five evidence-backed paid buyer decision checks and no free data leakage.");
